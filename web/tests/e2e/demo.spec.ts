import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";
test("visitor can receive stock, search products, reject overselling, and export", async ({ page }) => {
  await page.goto("/demo");
  await expect(page.getByRole("heading", { name: "Let's take stock." })).toBeVisible();
  await page.getByRole("button", { name: "Inventory", exact: false }).first().click();
  await page.getByLabel("Search inventory").fill("PKG-002");
  await expect(page.getByRole("row").filter({ hasText: "Recycled packing tape" })).toBeVisible();
  await page.getByRole("button", { name: "Stock", exact: true }).click();
  await page.getByLabel("Quantity (whole units)").fill("10");
  await page.getByLabel("Reference / reason").fill("Browser test receipt");
  await page.getByRole("button", { name: "Post movement", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Stock movement posted");
  await expect(page.getByRole("row").filter({ hasText: "Recycled packing tape" })).toContainText("28");
  await page.getByRole("button", { name: "Stock", exact: true }).click();
  await page.getByLabel("Movement type").selectOption("issue");
  await page.getByLabel("Quantity (whole units)").fill("999");
  await page.getByLabel("Reference / reason").fill("Browser test oversell");
  await page.getByRole("button", { name: "Post movement", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("alert")).toContainText("not enough stock");
  await page.getByRole("button", { name: "Close dialog" }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export CSV", exact: true }).click();
  expect((await download).suggestedFilename()).toContain(".csv");
});
test("desktop and mobile pages render without browser exceptions", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await mkdir("../docs/screenshots", { recursive: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await page.screenshot({ path: "../docs/screenshots/landing.png", fullPage: true });
  await page.goto("/demo");
  await page.screenshot({ path: "../docs/screenshots/dashboard.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".sidebar")).toBeHidden();
  const overflow = await page.evaluate(() => ({ viewport: window.innerWidth, document: document.documentElement.scrollWidth, elements: [...document.querySelectorAll("*")].filter((element) => { const rect = element.getBoundingClientRect(); return rect.right > window.innerWidth && rect.left >= 0; }).slice(0, 25).map((element) => ({ tag: element.tagName, className: element.className, width: element.getBoundingClientRect().width, overflow: getComputedStyle(element).overflowX })) }));
  expect(overflow.document, JSON.stringify(overflow)).toBeLessThanOrEqual(overflow.viewport);
  await page.screenshot({ path: "../docs/screenshots/mobile.png", fullPage: true });
  expect(errors).toEqual([]);
});
test("public metadata and report exports work; authenticated data stays protected", async ({ request }) => {
  const health = await request.get("/api/health");
  expect(health.ok()).toBeTruthy();
  const sitemap = await request.get("/sitemap.xml");
  expect(await sitemap.text()).not.toContain("/dashboard");
  const pdf = await request.get("/api/reports?demo=1&format=pdf");
  expect(pdf.status(), "PDF endpoint must return a successful response").toBe(200);
  expect(pdf.headers()["content-type"]).toContain("application/pdf");
  expect((await pdf.body()).subarray(0, 4).toString()).toBe("%PDF");
  const excel = await request.get("/api/reports?demo=1&format=xlsx");
  expect(excel.ok()).toBeTruthy();
  const privateReport = await request.get("/api/reports?format=csv", { maxRedirects: 0 });
  expect([303, 307, 401]).toContain(privateReport.status());
});
test("PDF download stays on the dashboard and produces a PDF file", async ({ page }) => {
  await page.goto("/demo");
  await page.getByRole("button", { name: "Reports", exact: true }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  expect((await download).suggestedFilename()).toBe("stockroom-inventory.pdf");
  await expect(page).toHaveURL(/\/demo$/);
  await expect(page.getByRole("status")).toContainText("PDF report exported.");
});
test("report failure leaves the dashboard usable and displays an error", async ({ page }) => {
  await page.route("**/api/reports?*", (route) => route.fulfill({ status: 500, body: "" }));
  await page.goto("/demo");
  await page.getByRole("button", { name: "Reports", exact: true }).click();
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("The report could not be downloaded.");
  await expect(page).toHaveURL(/\/demo$/);
});
