import { createClient } from "@supabase/supabase-js";
import { loadEnvFile } from "node:process";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import assert from "node:assert/strict";
loadEnvFile(".env.local");
const fixture = JSON.parse(await readFile(".test-fixture.json", "utf8"));
const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, { auth: { persistSession: false } });
const signedIn = await supabase.auth.signInWithPassword({ email: fixture.email, password: fixture.password });
assert.ifError(signedIn.error);
const created = await supabase.rpc("create_workspace", { p_name: "Stockroom verification fixture", p_currency: "NZD" });
assert.ifError(created.error);
const org = created.data;
const supplier = await supabase.from("suppliers").insert({ organization_id: org, name: "Verification supplier", email: "", phone: "", lead_time_days: 3 }).select().single();
assert.ifError(supplier.error);
const product = await supabase.from("products").insert({ organization_id: org, name: "Concurrency verification stock", sku: "VERIFY-" + randomUUID().slice(0, 8), category: "Verification", supplier_id: supplier.data.id, reorder_point: 3, unit_cost_cents: 100 }).select().single();
assert.ifError(product.error);
const argumentsFor = (kind, quantity, key) => ({ p_organization: org, p_product: product.data.id, p_kind: kind, p_quantity: quantity, p_unit_cost: 100, p_reason: "Automated full-stack verification", p_idempotency: key });
const receiptKey = randomUUID();
const receipt = await supabase.rpc("post_stock", argumentsFor("receipt", 10, receiptKey));
assert.ifError(receipt.error);
const replay = await supabase.rpc("post_stock", argumentsFor("receipt", 10, receiptKey));
assert.equal(replay.data, receipt.data);
const issues = await Promise.all([supabase.rpc("post_stock", argumentsFor("issue", 7, randomUUID())), supabase.rpc("post_stock", argumentsFor("issue", 7, randomUUID()))]);
assert.equal(issues.filter((r) => !r.error).length, 1);
assert.equal(issues.filter((r) => r.error?.message.includes("insufficient stock")).length, 1);
const balance = await supabase.from("inventory_balances").select().eq("organization_id", org).eq("product_id", product.data.id).single();
assert.ifError(balance.error);
assert.equal(Number(balance.data.quantity), 3);
assert.equal(Number(balance.data.value_cents), 300);
await supabase.auth.signOut();
console.log("PASS: real Supabase authentication, workspace onboarding, supplier/product persistence, stock receipt, retry idempotency, concurrent oversell rejection, and valuation.");
